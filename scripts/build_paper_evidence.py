"""Rebuild paper tables from completed local evaluations; never train or evaluate."""
import csv
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'reports' / 'paper_track'
VARIANTS = {
    'PPO baseline (8)': 'runs/ppo_novelty_20261023/baseline',
    'PPO novelty (8)': 'runs/ppo_novelty_20261023/novelty',
    'Grid control + novelty (16)': 'runs/ppo_action_memory_20261023/grid_control',
    'Memory + novelty (16)': 'runs/ppo_action_memory_20261023/memory_novelty',
    'Memory only (16)': 'runs/ppo_action_memory_20261023/memory_only',
}

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for variant, folder in VARIANTS.items():
        for game in ['ft09', 'dc22', 'g50t', 'm0r0']:
            for seed in range(3):
                for mode in ['sampled', 'greedy']:
                    base = ROOT / folder
                    if variant == 'PPO baseline (8)' and mode == 'greedy':
                        # The historical greedy baseline uses a different directory layout.
                        continue
                    path = base / game / 'eval' / f'seed{seed}_{mode}' / 'episodes.csv'
                    data = list(csv.DictReader(path.open(newline='')))
                    assert len(data) == 20, path
                    exported = OUT / 'evaluation_logs' / path.relative_to(ROOT / 'runs')
                    exported.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(path, exported)
                    rows.append(dict(variant=variant, game=game, seed=seed, mode=mode,
                        episodes=len(data), episodes_with_level=sum(int(r['levels_completed']) > 0 for r in data),
                        levels=sum(int(r['levels_completed']) for r in data),
                        wins=sum(int(r['won']) for r in data),
                        actions=sum(int(r['actions_used']) for r in data),
                        wall_seconds=round(sum(float(r['wall_s']) for r in data), 2),
                        source=path.relative_to(ROOT).as_posix(),
                        exported_source=exported.relative_to(OUT).as_posix()))
    with (OUT / 'verified_results.csv').open('w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    lines = ['# Verified local evidence', '',
        'Generated by `python scripts/build_paper_evidence.py`. Each cell lists successful episodes out of 20 for training seeds 0, 1, 2. Success here means at least one level completed, not a game won. These are frozen-policy evaluations on development games used for training; they are not held-out or official scores.', '',
        '| Variant | ft09 | dc22 | g50t | m0r0 |', '|---|---|---|---|---|']
    for variant in VARIANTS:
        cells = []
        for game in ['ft09', 'dc22', 'g50t', 'm0r0']:
            selected = [r for r in rows if r['variant'] == variant and r['game'] == game and r['mode'] == 'sampled']
            cells.append(', '.join(str(r['episodes_with_level']) for r in selected))
        lines.append('| ' + ' | '.join([variant] + cells) + ' |')
    assert all(r['wins'] == 0 for r in rows)
    assert all(r['levels'] == 0 for r in rows if r['mode'] == 'greedy')
    lines += ['', f'Audited {len(rows)} evaluation files ({sum(r["episodes"] for r in rows)} episodes). No full-game wins. All audited greedy evaluations completed zero levels. Historical baseline greedy files are excluded from this aggregate because their layout differs.', '',
        'The CSV includes original source paths, published copies under `evaluation_logs/`, action totals and recorded evaluation wall times. Wall times exclude orchestration overhead. This is an evidence export, not a new benchmark run.', '',
        'Only three independent training seeds exist per condition. Twenty sampled rollouts per checkpoint do not constitute twenty independent trained models. Evaluation seeds control action sampling, not game layout generation.', '',
        'DQN and random-policy historical figures are deliberately excluded: complete matched evaluation evidence was not available for this export. No PPO-versus-DQN superiority claim is supported.']
    (OUT / 'EVIDENCE.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(json.dumps({'evaluation_files': len(rows), 'episodes': sum(r['episodes'] for r in rows), 'output': str(OUT)}))

if __name__ == '__main__':
    main()
